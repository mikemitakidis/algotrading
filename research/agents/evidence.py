"""research.agents.evidence — lane E report: roles, permissions and the mock research run.

    python -m research.agents.evidence --out docs/research/evidence/lane_e_agents
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Optional, Sequence

from research.agents import mock as MK
from research.agents.roles import ACTIONS, NEVER, ROLES


def render(r: MK.MockRun, seconds: float) -> str:
    acts = sorted(ACTIONS - NEVER)
    L = ["# Lane E — research-agent foundations: roles, knowledge library, offline mock run", "",
         "> Offline and deterministic. No model, network, API key, scheduler or paid service is involved. "
         "The mock shows the governed path and its guards; its synthetic evaluation says nothing about real "
         "markets.", "",
         "Generated by `python -m research.agents.evidence` in %.0f s. Run digest `%s`." % (seconds, r.digest[:16]), "",
         "## 1. Roles and permissions", "",
         "Allowed actions per role (✓). Everything else is denied and logged. These actions are denied to "
         "**every** role whatever the configuration: %s." % ", ".join("`%s`" % a for a in sorted(NEVER)), "",
         "| role | " + " | ".join("`%s`" % a for a in acts) + " |", "|---|" + "---|" * len(acts)]
    for name, role in ROLES.items():
        L.append("| %s%s | %s |" % (name, " (deterministic)" if role.deterministic else "",
                                    " | ".join("✓" if a in role.allowed else "" for a in acts)))
    L += ["", "## 2. The mock run", "", r.report, "",
          "**Refusals (guards that fired):**", ""] + ["- %s" % x for x in r.refusals] + [
          "", "**Knowledge library after the run:** %s" % json.dumps(
              {k: v for k, v in r.kb.items() if k != "status"}), "",
          "**Permission decisions logged:** %d (%d allowed, %d denied). Ledger: %d entries, chain verified = %s." % (
              len(r.decisions), sum(d["allowed"] for d in r.decisions), sum(not d["allowed"] for d in r.decisions),
              r.ledger_entries, r.ledger_ok), "",
          "**Generated-code lint** (text only, never executed): %s" % ", ".join(
              sorted({f["capability"] for f in r.extra["lint"]["capability_findings"]})), "",
          "## 3. What is still required before any real agent runs", "",
          "- An OS/container sandbox for any generated code: no secrets, no network, read-only inputs. "
          "`research.boundary` is a lint, not a sandbox.",
          "- Operator approval for any model or API usage, any scheduled or paid agent, and any write beyond "
          "an isolated branch.",
          "- A separately held authority for pre-registration attestations and holdout releases (lane B).",
          "- Operator verification of every citation an agent records (`verify_source` accepts only "
          "`operator:` identities).", ""]
    return "\n".join(L)


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    t0 = time.time()
    r = MK.run()
    secs = time.time() - t0
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".md").write_text(render(r, secs))
    out.with_suffix(".json").write_text(json.dumps({"digest": r.digest, "refusals": r.refusals, "kb": r.kb,
                                                    "evaluation": r.evaluation, "report_card": r.report_card,
                                                    "prereg": r.prereg_outcome, "decisions": r.decisions,
                                                    "ledger_entries": r.ledger_entries, "ledger_ok": r.ledger_ok},
                                                   indent=1, sort_keys=True, default=str) + "\n")
    print("wrote %s.{md,json}" % out, file=sys.stderr)
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
